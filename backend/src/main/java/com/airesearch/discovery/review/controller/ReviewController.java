package com.airesearch.discovery.review.controller;

import com.airesearch.discovery.auth.security.UserPrincipal;
import com.airesearch.discovery.review.dto.ReviewDtos.*;
import com.airesearch.discovery.review.service.LiteratureReviewService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.*;

import java.util.List;
import java.util.UUID;

@RestController
@RequestMapping("/api/v1/reviews")
@Tag(name = "Literature Reviews", description = "Evidence-backed automated literature reviews and citation export")
public class ReviewController {

    private final LiteratureReviewService reviewService;

    public ReviewController(LiteratureReviewService reviewService) {
        this.reviewService = reviewService;
    }

    @PostMapping("/generate")
    @Operation(summary = "Generate an evidence-backed literature review grounded in retrieved chunks")
    public ResponseEntity<ReviewDetailDto> generateReview(
            @Valid @RequestBody GenerateReviewRequest request,
            @AuthenticationPrincipal UserPrincipal principal) {

        ReviewDetailDto review = reviewService.generateReview(request, principal.getId());
        return ResponseEntity.status(HttpStatus.CREATED).body(review);
    }

    @GetMapping
    @Operation(summary = "List all literature reviews generated by current user")
    public ResponseEntity<List<ReviewSummaryDto>> listReviews(@AuthenticationPrincipal UserPrincipal principal) {
        List<ReviewSummaryDto> reviews = reviewService.listReviews(principal.getId());
        return ResponseEntity.ok(reviews);
    }

    @GetMapping("/{id}")
    @Operation(summary = "Get literature review with audited paragraph-to-chunk evidence links")
    public ResponseEntity<ReviewDetailDto> getReviewDetail(
            @PathVariable UUID id,
            @AuthenticationPrincipal UserPrincipal principal) {

        ReviewDetailDto review = reviewService.getReviewDetail(id, principal.getId());
        return ResponseEntity.ok(review);
    }

    @GetMapping("/{id}/evidence")
    @Operation(summary = "Inspect exact source chunks and citation snippets backing review statements")
    public ResponseEntity<List<ReviewEvidenceItem>> getReviewEvidence(
            @PathVariable UUID id,
            @AuthenticationPrincipal UserPrincipal principal) {

        ReviewDetailDto review = reviewService.getReviewDetail(id, principal.getId());
        return ResponseEntity.ok(review.evidence());
    }

    @GetMapping("/{id}/export")
    @Operation(summary = "Export review in Markdown (.md) or BibTeX (.bib) format")
    public ResponseEntity<String> exportReview(
            @PathVariable UUID id,
            @RequestParam(defaultValue = "markdown") String format,
            @AuthenticationPrincipal UserPrincipal principal) {

        if ("bibtex".equalsIgnoreCase(format)) {
            String bibtex = reviewService.exportBibTeX(id, principal.getId());
            return ResponseEntity.ok()
                    .header(HttpHeaders.CONTENT_DISPOSITION, "attachment; filename=\"citations_" + id + ".bib\"")
                    .contentType(MediaType.TEXT_PLAIN)
                    .body(bibtex);
        } else {
            String markdown = reviewService.exportMarkdown(id, principal.getId());
            return ResponseEntity.ok()
                    .header(HttpHeaders.CONTENT_DISPOSITION, "attachment; filename=\"review_" + id + ".md\"")
                    .contentType(MediaType.TEXT_MARKDOWN)
                    .body(markdown);
        }
    }
}
